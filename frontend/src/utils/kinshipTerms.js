/** 取称谓文案;缺失码退化到「亲属」。 */
export function kinshipLabel(code, locale = 'zh-CN') {
  if (!code) return ''
  const item = TERMS[code]
  if (!item) return locale === 'en' ? 'Relative' : '亲属'
  return locale === 'en' ? item.en : item.zh
}

